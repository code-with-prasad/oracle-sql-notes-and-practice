
-- CR : Count the no of A Present in NARAYAN?--O/P 3 , GOOGLE - O - 2
SELECT LENGTH('NARAYAN') - LENGTH(REPLACE('NARAYAN','A','')) FROM DUAL;
SELECT LENGTH('GOOGLE') - LENGTH(REPLACE('GOOGLE','O','')) FROM DUAL;

--CR : I LOVE MY INDIA –COUNT THE NO OF WORDS PRESENT? --O/P 4
SELECT LENGTH('I LOVE MY INDIA') - LENGTH(REPLACE('I LOVE MY INDIA',' ',''))+1 AS WORD_COUNT FROM DUAL;
--CR: 'ABCPQRABCDEFABC' – COUNT  THE REPETATION OF ABC ?--O/P -3 
SELECT LENGTH(REPLACE('ABCPQRABCDEFABC','ABC',' ')) - LENGTH(REPLACE('ABCPQRABCDEFABC','ABC','')) AS "  " FROM DUAL;
SELECT (LENGTH('ABCPQRABCDEFABC') - LENGTH(REPLACE('ABCPQRABCDEFABC','ABC','')) ) / LENGTH('ABC') AS TOTAL_COUNT FROM DUAL;
